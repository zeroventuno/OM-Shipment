export const isRelation = (v: string): v is Relation => (RELATIONS as readonly string[]).includes(v);

/** Nome da relação no idioma pedido. Texto livre antigo sai como foi escrito. */
export const relationLabel = (lang: NfcLanguage, value: string) => (isRelation(value) ? RELATION_LABELS[lang][value] : value);

/** Número para o link tel:(só dígitos e o + inicial). */
export const telHref = (phone: string) => {
  const p = phone.trim();
  const digits = p.replace(/[^\d]/g, "");
  return digits ? `tel:${p.startsWith("+") || p.startsWith("00") ? "+" + digits.replace(/^00/, "") : digits}` : "";
};

/** "Cristiano Cunha" → ["Cristiano", "Cunha"]: o sobrenome sai em cinza, como no cartão de visitas. */
export function splitName(name: string): [string, string] {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  return [parts[0] ?? "", parts.slice(1).join(" ")];
}

/** Endereço público do chip. Numa prévia da Vercel (protegida por login), usa o de produção. */
export function publicOrigin(origin: string): string {
  const host = new URL(origin).host;
  return /\.vercel\.app$/.test(host) && host !== "om-shipment.vercel.app" ? "https://om-shipment.vercel.app" : origin;
}

